    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            if (txtCodigo.getText().trim().isEmpty()
                    || txtNombre.getText().trim().isEmpty()
                    || txtDescripcion.getText().trim().isEmpty()
                    || txtCostoManoObra.getText().trim().isEmpty()
                    || txtTiempoEstimado.getText().trim().isEmpty()) {

                JOptionPane.showMessageDialog(this, "Completa todos los campos.");
                return;
            }

            Servicio s = crearServicioPorTipo();
            s.setCodigo(txtCodigo.getText().trim());
            s.setNombre(txtNombre.getText().trim());
            s.setDescripcion(txtDescripcion.getText().trim());
            s.setNivel(Integer.parseInt(cmbNivel.getSelectedItem().toString()));
            s.setCostoManoObra(Double.parseDouble(txtCostoManoObra.getText().trim()));
            s.setTiempoEstimado(Double.parseDouble(txtTiempoEstimado.getText().trim()));
            s.setEstado(cmbEstado.getSelectedItem().toString());

            if (controlador.guardar(s)) {
                JOptionPane.showMessageDialog(this, "Servicio registrado correctamente.");
                limpiarCampos();
                cargarServicios();
            }

        } catch (SQLException | NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        } 
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        try {
            if (txtIdServicio.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Selecciona un servicio.");
                return;
            }

            Servicio s = crearServicioPorTipo();
            s.setIdServicio(Integer.parseInt(txtIdServicio.getText()));
            s.setCodigo(txtCodigo.getText().trim());
            s.setNombre(txtNombre.getText().trim());
            s.setDescripcion(txtDescripcion.getText().trim());
            s.setNivel(Integer.parseInt(cmbNivel.getSelectedItem().toString()));
            s.setCostoManoObra(Double.parseDouble(txtCostoManoObra.getText().trim()));
            s.setTiempoEstimado(Double.parseDouble(txtTiempoEstimado.getText().trim()));
            s.setEstado(cmbEstado.getSelectedItem().toString());

            if (controlador.actualizar(s)) {
                JOptionPane.showMessageDialog(this, "Servicio actualizado correctamente.");
                limpiarCampos();
                cargarServicios();
                
            }

        } catch (SQLException | NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        } 
    }//GEN-LAST:event_btnActualizarActionPerformed

    private Servicio crearServicioPorTipo() {

        String tipo = cmbTipoServicio.getSelectedItem().toString();

        Servicio servicio;

        switch (tipo) {
            case "MANTENIMIENTO":
                servicio = new ServicioMantenimiento();
                break;

            case "REPARACION":
                servicio = new ServicioReparacion();
                break;

            case "DIAGNOSTICO":
                servicio = new ServicioDiagnostico();
                break;

            case "CAMBIO_MOTOR":
                servicio = new ServicioCambioMotor();
                break;

            default:
                servicio = new Servicio();
                break;
        }

        return servicio;
    }

