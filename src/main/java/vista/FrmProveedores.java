    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            if (txtNombre.getText().trim().isEmpty()
                    || txtTelefono.getText().trim().isEmpty()) {

                JOptionPane.showMessageDialog(this,
                        "El nombre y teléfono son obligatorios.");
                return;
            }

            Proveedor p = new Proveedor();

            p.setNombre(txtNombre.getText().trim());
            p.setTelefono(txtTelefono.getText().trim());
            p.setCorreo(txtCorreo.getText().trim());
            p.setDireccion(txtDireccion.getText().trim());
            p.setEstado(cmbEstado.getSelectedItem().toString());

            if (controlador.guardar(p)) {
                JOptionPane.showMessageDialog(this,
                        "Proveedor registrado correctamente.");

                limpiarCampos();
                cargarProveedores();
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Error al guardar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        try {
            if (txtIdProveedor.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(this,
                        "Selecciona un proveedor.");
                return;
            }

            Proveedor p = new Proveedor();

            p.setIdProveedor(Integer.parseInt(txtIdProveedor.getText()));
            p.setNombre(txtNombre.getText().trim());
            p.setTelefono(txtTelefono.getText().trim());
            p.setCorreo(txtCorreo.getText().trim());
            p.setDireccion(txtDireccion.getText().trim());
            p.setEstado(cmbEstado.getSelectedItem().toString());

            if (controlador.actualizar(p)) {
                JOptionPane.showMessageDialog(this,
                        "Proveedor actualizado correctamente.");

                limpiarCampos();
                cargarProveedores();
            }

        } catch (SQLException | NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "Error al actualizar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

