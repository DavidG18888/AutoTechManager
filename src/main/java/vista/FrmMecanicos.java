    private void cargarMecanicos() {
        try {
            // Limpiar los registros anteriores de la tabla
            modeloTabla.setRowCount(0);

            // Consultar todos los mecánicos registrados
            List<Mecanico> mecanicos = controlador.listar();

            // Recorrer la lista y agregar cada mecánico a la tabla
            for (Mecanico m : mecanicos) {
                modeloTabla.addRow(new Object[]{
                    m.getIdMecanico(),
                    m.getNombre(),
                    m.getTelefono(),
                    m.getEspecialidad(),
                    m.getEstado()
                });
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Error al cargar mecánicos: " + e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
        }
    }
