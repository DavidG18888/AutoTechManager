    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            if (txtNombre.getText().trim().isEmpty()
                    || txtTelefono.getText().trim().isEmpty()
                    || txtEspecialidad.getText().trim().isEmpty()) {

                JOptionPane.showMessageDialog(this,
                        "Completa todos los campos.");
                return;
            }

            Mecanico mecanico = new Mecanico();
            mecanico.setNombre(txtNombre.getText().trim());
            mecanico.setTelefono(txtTelefono.getText().trim());
            mecanico.setEspecialidad(txtEspecialidad.getText().trim());
            mecanico.setEstado(cmbEstado.getSelectedItem().toString());

            if (controlador.guardar(mecanico)) {
                JOptionPane.showMessageDialog(this,
                        "Mecánico registrado correctamente.");
                limpiarCampos();
                cargarMecanicos();
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        try {
            if (txtIdMecanico.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(this,
                        "Selecciona un mecánico.");
                return;
            }

            Mecanico mecanico = new Mecanico();
            mecanico.setIdMecanico(Integer.parseInt(txtIdMecanico.getText()));
            mecanico.setNombre(txtNombre.getText().trim());
            mecanico.setTelefono(txtTelefono.getText().trim());
            mecanico.setEspecialidad(txtEspecialidad.getText().trim());
            mecanico.setEstado(cmbEstado.getSelectedItem().toString());

            if (controlador.actualizar(mecanico)) {
                JOptionPane.showMessageDialog(this,
                        "Mecánico actualizado correctamente.");
                limpiarCampos();
                cargarMecanicos();
            }

        } catch (SQLException | NumberFormatException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

