    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            if (txtNombre.getText().trim().isEmpty()
                    || txtDni.getText().trim().isEmpty()
                    || txtTelefono.getText().trim().isEmpty()) {

                JOptionPane.showMessageDialog(this,
                        "Completa el nombre, DNI y teléfono.");
                return;
            }

            Cliente cliente = new Cliente();

            cliente.setNombre(txtNombre.getText().trim());
            cliente.setDni(txtDni.getText().trim());
            cliente.setTelefono(txtTelefono.getText().trim());
            cliente.setCorreo(txtCorreo.getText().trim());
            cliente.setDireccion(txtDireccion.getText().trim());
            cliente.setEstado("ACTIVO");

            if (controlador.guardar(cliente)) {
                JOptionPane.showMessageDialog(this,
                        "Cliente registrado correctamente.");
                limpiarCampos();
                cargarClientes();
            } else {
                JOptionPane.showMessageDialog(this,
                        "No se pudo registrar el cliente.");
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Error al guardar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        try {
            if (txtIdCliente.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(this,
                        "Selecciona un cliente de la tabla.");
                return;
            }

            Cliente cliente = new Cliente();

            cliente.setIdCliente(Integer.parseInt(txtIdCliente.getText()));
            cliente.setNombre(txtNombre.getText().trim());
            cliente.setDni(txtDni.getText().trim());
            cliente.setTelefono(txtTelefono.getText().trim());
            cliente.setCorreo(txtCorreo.getText().trim());
            cliente.setDireccion(txtDireccion.getText().trim());

            if (controlador.actualizar(cliente)) {
                JOptionPane.showMessageDialog(this,
                        "Cliente actualizado correctamente.");
                limpiarCampos();
                cargarClientes();
            } else {
                JOptionPane.showMessageDialog(this,
                        "No se pudo actualizar el cliente.");
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Error al actualizar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnDesactivarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDesactivarActionPerformed
        try {
            if (txtIdCliente.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(this,
                        "Selecciona un cliente de la tabla.");
                return;
            }

            int respuesta = JOptionPane.showConfirmDialog(this,
                    "¿Deseas desactivar este cliente?",
                    "Confirmar desactivación",
                    JOptionPane.YES_NO_OPTION);

            if (respuesta == JOptionPane.YES_OPTION) {

                int id = Integer.parseInt(txtIdCliente.getText());

                if (controlador.cambiarEstado(id, "INACTIVO")) {
                    JOptionPane.showMessageDialog(this,
                            "Cliente desactivado correctamente.");
                    limpiarCampos();
                    cargarClientes();
                } else {
                    JOptionPane.showMessageDialog(this,
                            "No se pudo desactivar el cliente.");
                }
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Error al desactivar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnDesactivarActionPerformed

