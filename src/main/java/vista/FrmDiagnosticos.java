    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {

            if (cmbOrden.getSelectedItem() == null) {
                JOptionPane.showMessageDialog(this,
                        "Seleccione una orden de trabajo.");
                return;
            }

            if (txtDescripcion.getText().trim().isEmpty()
                    || txtRecomendaciones.getText().trim().isEmpty()
                    || txtEvidenciasTecnicas.getText().trim().isEmpty()
                    || txtCausa.getSelectedIndex() <= 0) {

                JOptionPane.showMessageDialog(this,
                        "Complete todos los campos.");
                return;
            }

            int idOrden = Integer.parseInt(
                    cmbOrden.getSelectedItem().toString().split(" - ")[0]
            );

            Diagnostico diagnostico = new Diagnostico();

            diagnostico.setIdOrden(idOrden);
            diagnostico.setFecha(LocalDateTime.now());
            diagnostico.setDescripcion(
                    txtDescripcion.getText().trim()
            );
            diagnostico.setCausa(
                    txtCausa.getSelectedItem().toString()
            );
            diagnostico.setRecomendaciones(
                    txtRecomendaciones.getText().trim()
            );
            diagnostico.setEvidenciasTecnicas(
                    txtEvidenciasTecnicas.getText().trim()
            );

            boolean guardado = diagnosticoControlador.guardar(diagnostico);

            if (guardado) {
                JOptionPane.showMessageDialog(this,
                        "Diagnóstico registrado correctamente.");

                limpiarCampos();
                cargarDiagnosticos();
            }

        } catch (SQLException ex) {

            JOptionPane.showMessageDialog(this,
                    "Error al guardar el diagnóstico: " + ex.getMessage());

        } catch (IllegalArgumentException ex) {

            JOptionPane.showMessageDialog(this,
                    ex.getMessage());
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

