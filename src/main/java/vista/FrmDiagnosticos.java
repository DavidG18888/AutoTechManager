    private void limpiarCampos() {

        txtIdDiagnostico.setText("");

        txtFecha.setText(
                LocalDateTime.now().format(formatoFecha)
        );

        txtDescripcion.setText("");
        txtRecomendaciones.setText("");
        txtEvidenciasTecnicas.setText("");

        if (txtCausa.getItemCount() > 0) {
            txtCausa.setSelectedIndex(0);
        }

        if (cmbOrden.getItemCount() > 0) {
            cmbOrden.setSelectedIndex(0);
        }

        modeloTabla.setRowCount(0);
    }
