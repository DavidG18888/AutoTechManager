    public FrmDiagnosticos(int idOrden) {
        this();

        for (int i = 0; i < cmbOrden.getItemCount(); i++) {
            String opcion = cmbOrden.getItemAt(i);

            if (opcion.startsWith(idOrden + " - ")) {
                cmbOrden.setSelectedIndex(i);
                break;
            }
        }

        cargarDiagnosticos();
        setLocationRelativeTo(null);
    }
    private void cargarOrdenes() {
        try {
            cmbOrden.removeAllItems();

            List<OrdenTrabajo> lista = ordenControlador.listar();

            for (OrdenTrabajo orden : lista) {
                cmbOrden.addItem(
                    orden.getIdOrden() + " - " + orden.getEstado()
                );
            }

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this,
                    "Error al cargar las órdenes: " + ex.getMessage());
        }
    }

    private void cargarDiagnosticos() {
        try {
            modeloTabla.setRowCount(0);

            if (cmbOrden.getSelectedItem() == null) {
                return;
            }

            int idOrden = Integer.parseInt(
                cmbOrden.getSelectedItem().toString().split(" - ")[0]
            );

            List<Diagnostico> lista =
                    diagnosticoControlador.listarPorOrden(idOrden);

            for (Diagnostico d : lista) {
                modeloTabla.addRow(new Object[]{
                    d.getIdDiagnostico(),
                    d.getIdOrden(),
                    d.getFecha(),
                    d.getDescripcion(),
                    d.getCausa(),
                    d.getRecomendaciones(),
                    d.getEvidenciasTecnicas()
                });
            }

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this,
                    "Error al cargar diagnósticos: " + ex.getMessage());
        }
    }
