    private int obtenerIdServicioSeleccionado() {
        int fila = tablaServicios.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(this,
                    "Primero seleccione un servicio.");
            return -1;
        }

        return Integer.parseInt(
                tablaServicios.getValueAt(fila, 0).toString()
        );
    }
    private void cargarServicios() {
        try {
            modeloTabla.setRowCount(0);

            List<Servicio> servicios = controlador.listar();

            for (Servicio s : servicios) {
                modeloTabla.addRow(new Object[]{
                    s.getIdServicio(),
                    s.getCodigo(),
                    s.getNombre(),
                    s.getDescripcion(),
                    s.getNivel(),
                    s.getCostoManoObra(),
                    s.getTiempoEstimado(),
                    s.getEstado(),
                    s.obtenerTipoServicio()
                });
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Error al cargar servicios: " + e.getMessage());
        }
    }
    
    private void seleccionarServicio() {
        int fila = tablaServicios.getSelectedRow();

        if (fila >= 0) {
            txtIdServicio.setText(modeloTabla.getValueAt(fila, 0).toString());
            txtCodigo.setText(modeloTabla.getValueAt(fila, 1).toString());
            txtNombre.setText(modeloTabla.getValueAt(fila, 2).toString());
            txtDescripcion.setText(modeloTabla.getValueAt(fila, 3).toString());
            cmbNivel.setSelectedItem(modeloTabla.getValueAt(fila, 4).toString());
            txtCostoManoObra.setText(modeloTabla.getValueAt(fila, 5).toString());
            txtTiempoEstimado.setText(modeloTabla.getValueAt(fila, 6).toString());
            cmbEstado.setSelectedItem(modeloTabla.getValueAt(fila, 7).toString());
            cmbTipoServicio.setSelectedItem(modeloTabla.getValueAt(fila, 8).toString());
        }
    }

