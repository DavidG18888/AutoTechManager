    private void seleccionarMecanico() {
    int fila = tablaMecanicos.getSelectedRow();

    if (fila >= 0) {
        txtIdMecanico.setText(modeloTabla.getValueAt(fila, 0).toString());
        txtNombre.setText(modeloTabla.getValueAt(fila, 1).toString());
        txtTelefono.setText(modeloTabla.getValueAt(fila, 2).toString());
        txtEspecialidad.setText(modeloTabla.getValueAt(fila, 3).toString());
        cmbEstado.setSelectedItem(modeloTabla.getValueAt(fila, 4).toString());
    }
}

    private void limpiarCampos() {
        txtIdMecanico.setText("");
        txtNombre.setText("");
        txtTelefono.setText("");
        txtEspecialidad.setText("");
        cmbEstado.setSelectedItem("ACTIVO");
        tablaMecanicos.clearSelection();
        txtNombre.requestFocus();
    }
    
    
