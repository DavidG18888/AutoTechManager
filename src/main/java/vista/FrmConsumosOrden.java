    private void cargarOrdenes() {
        try {
            cmbOrden.removeAllItems();

            List<OrdenTrabajo> ordenes = ordenControlador.listar();

            for (OrdenTrabajo orden : ordenes) {
                cmbOrden.addItem(orden.getIdOrden() + " - Orden de trabajo");
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Error al cargar órdenes: " + e.getMessage());
        }
    }

    private void cargarRepuestos() {
        try {
            cmbRepuesto.removeAllItems();

            List<Repuesto> repuestos = inventarioServicio.listar();

            for (Repuesto repuesto : repuestos) {
                if (repuesto.getExistencia() > 0) {
                    cmbRepuesto.addItem(
                            repuesto.getIdRepuesto() + " - " + repuesto.getNombre());
                }
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Error al cargar repuestos: " + e.getMessage());
        }
    }

    private int obtenerIdSeleccionado(javax.swing.JComboBox<String> combo) {
        Object seleccionado = combo.getSelectedItem();

        if (seleccionado == null) {
            return -1;
        }

        try {
            return Integer.parseInt(seleccionado.toString().split(" - ")[0]);
        } catch (NumberFormatException e) {
            return -1;
        }
    }

    private void mostrarCostoRepuesto() {
        int idRepuesto = obtenerIdSeleccionado(cmbRepuesto);

        if (idRepuesto <= 0) {
            txtCostoUnitario.setText("");
            calcularTotal();
            return;
        }

        try {
            Repuesto repuesto = inventarioServicio.buscarPorId(idRepuesto);

            if (repuesto != null) {
                txtCostoUnitario.setText(String.valueOf(repuesto.getCosto()));
                calcularTotal();
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Error al consultar repuesto: " + e.getMessage());
        }
    }

    private void calcularTotal() {
        try {
            String cantidadTexto = txtCantidad.getText().trim();
            String costoTexto = txtCostoUnitario.getText().trim();

            if (cantidadTexto.isEmpty() || costoTexto.isEmpty()) {
                txtTotal.setText("");
                return;
            }

            int cantidad = Integer.parseInt(cantidadTexto);
            double costo = Double.parseDouble(costoTexto);

            if (cantidad <= 0) {
                txtTotal.setText("");
                return;
            }

            txtTotal.setText(formatoMoneda.format(cantidad * costo));

        } catch (NumberFormatException e) {
            txtTotal.setText("");
        }
    }

    private void cargarConsumosSeleccionados() {
        int idOrden = obtenerIdSeleccionado(cmbOrden);

        DefaultTableModel modelo =
                (DefaultTableModel) tablaConsumos.getModel();

        modelo.setRowCount(0);

        if (idOrden <= 0) {
            return;
        }

        try {
            List<ConsumoOrden> consumos =
                    inventarioServicio.listarConsumos(idOrden);

            for (ConsumoOrden consumo : consumos) {
                double total =
                        consumo.getCantidad() * consumo.getCostoUnitario();

                modelo.addRow(new Object[]{
                    consumo.getNombreRepuesto(),
                    consumo.getCantidad(),
                    formatoMoneda.format(consumo.getCostoUnitario()),
                    formatoMoneda.format(total)
                });
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Error al cargar consumos: " + e.getMessage());
        }
    }

    private void actualizarFecha() {
        txtFecha.setText(
                LocalDateTime.now().format(
                        DateTimeFormatter.ofPattern("dd/MM/yyyy HH:mm")
                )
        );
    }

    private void limpiarCampos() {
        cmbRepuesto.setSelectedIndex(-1);
        txtCantidad.setText("");
        txtCostoUnitario.setText("");
        txtTotal.setText("");
        actualizarFecha();
    }

    private void guardarConsumo() {
        int idOrden = obtenerIdSeleccionado(cmbOrden);
        int idRepuesto = obtenerIdSeleccionado(cmbRepuesto);

        if (idOrden <= 0 || idRepuesto <= 0) {
            JOptionPane.showMessageDialog(this,
                    "Seleccione una orden y un repuesto.");
            return;
        }

        int cantidad;

        try {
            cantidad = Integer.parseInt(txtCantidad.getText().trim());

            if (cantidad <= 0) {
                JOptionPane.showMessageDialog(this,
                        "La cantidad debe ser mayor que cero.");
                return;
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese una cantidad válida.");
            return;
        }

        try {
            boolean registrado = inventarioServicio.registrarConsumo(
                    idOrden, idRepuesto, cantidad);

            if (registrado) {
                JOptionPane.showMessageDialog(this,
                        "Consumo registrado correctamente.");

                cargarRepuestos();
                cargarConsumosSeleccionados();
                limpiarCampos();
            }

        } catch (IllegalArgumentException | SQLException e) {
            JOptionPane.showMessageDialog(this,
                    e.getMessage(),
                    "Error al registrar consumo",
                    JOptionPane.WARNING_MESSAGE);
        }
    }

